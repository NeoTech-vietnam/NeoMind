import test from 'node:test';
import assert from 'node:assert/strict';
import { reaNativeArguments, reaNativeToolDefinition } from '../dist/rea-native-mcp.js';

test('native REA identity is generated by the backend without exposing path/digest claims', () => {
  assert.deepEqual(reaNativeArguments('binary_session', {}), { expected_package_version: '6.7.0' });
  assert.throws(() => reaNativeArguments('binary_session', { expected_server_path: 'rea', expected_catalog_digest: '0'.repeat(64) }), /INPUT_INVALID/);
  assert.throws(() => reaNativeArguments('binary_session', { expected_package_version: '6.7.0 rollup?' }), /INPUT_INVALID/);
  const tool = reaNativeToolDefinition({ name: 'binary_session', inputSchema: { type: 'object' } });
  assert.deepEqual(Object.keys(tool.inputSchema.properties), ['expected_package_version']);
});
test('native REA narrows giant inline evidence and budgets before opening the original engine', () => {
  const id = `ev_${'a'.repeat(64)}`;
  assert.deepEqual(reaNativeArguments('inspect_analysis_view', { source: { kind: 'retained-evidence', evidence_id: id }, view: { kind: 'summary' } }).source.evidence_id, id);
  assert.throws(() => reaNativeArguments('inspect_analysis_view', { source: { kind: 'inline', evidence: {} }, view: { kind: 'summary' } }), /INPUT_INVALID/);
  assert.throws(() => reaNativeArguments('analyze_javascript_application', { input_path: 'research/public', analysis_timeout_ms: 300000 }), /INPUT_INVALID/);
  assert.throws(() => reaNativeArguments('open_binary', {}), /TOOL_UNSUPPORTED/);
  const tool = reaNativeToolDefinition({ name: 'inspect_analysis_view', inputSchema: { type: 'object' } });
  assert.ok(Buffer.byteLength(JSON.stringify(tool.inputSchema)) < 1500);
});
