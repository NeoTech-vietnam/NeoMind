function canonical(value: unknown): string {
  if (value === undefined) return 'null';
  if (!value || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
  return `{${Object.entries(value).sort(([a], [b]) => a.localeCompare(b)).map(([key, item]) => `${JSON.stringify(key)}:${canonical(item)}`).join(',')}}`;
}
function location(root: string, requestRef: string, knownRequest?: ProjectRecord): string {
  if (!requestPattern.test(requestRef)) fail('Use the request reference returned by the native request backend.');
  const request = knownRequest ?? getRecord(root, requestRef), folder = requestFolderForWorkflow(root, requestRef);
  if (request.meta.id !== requestRef || request.meta.data.kind !== 'workforce-request' || request.meta.data.process_contract !== nativeRequestContract || !folder)
    fail('This request does not use the native Local contract; its historical execution is unchanged.');
  return safePath(root, `.workforce/${folder.directory}/native/execution.json`);
}
function load(root: string, requestRef: string, knownRequest?: ProjectRecord): State {
  const path = location(root, requestRef, knownRequest), stat = lstatSync(path);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1 || stat.size > 4 * 1024 * 1024) fail('Native request state requires an ordinary bounded file.');
  const state = JSON.parse(readFileSync(path, 'utf8')) as State;
  if (state.schema_version !== 1 || state.process_contract !== nativeRequestContract || state.request_ref !== requestRef ||
      !Array.isArray(state.assignments) || !Array.isArray(state.checks) || !Array.isArray(state.record_ids))
    fail('Saved native request state needs reconciliation; no work was redispatched.');
  return state;
}
function save(root: string, state: State): void {
  state.updated_at = now();
  atomicWrite(location(root, state.request_ref), JSON.stringify(state, null, 2) + '\n');
}
function locked<T>(root: string, ref: string, action: (state: State) => T): T {
  return withOperationLock(root, `native-request-${hash(ref)}`, () => action(load(root, ref)));
}
function fingerprints(root: string, outputs: string[], row?: MonitorRow): Fingerprints {
  if (row) return row.files.fingerprints(outputs);
  return Object.fromEntries(outputs.map(path => {
    const file = safePath(root, path);
    if (!existsSync(file)) return [path, null];
    const stat = lstatSync(file);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1) fail('Native request products must be ordinary unlinked files.');
    if (stat.size > 20 * 1024 * 1024) fail('Native request product exceeds the hashing limit.');
    return [path, hash(readFileSync(file))];
  }));
}
function preservationBaseline(root: string, state: State): Fingerprints {
  const outputs = new Set(state.plan!.outputs.map(path => process.platform === 'win32' ? path.toLowerCase() : path));
  return fingerprints(root, [...ordinarySkillReceipts(root, state), ...sourceMembership(root, state).filter(path => {
    if (/^(?:\.git|\.workforce|\.neomind|\.taskforces|\.verythinker)(?:\/|$)/i.test(path) ||
        outputs.has(process.platform === 'win32' ? path.toLowerCase() : path)) return false;
    const file = safePath(root, path);
    if (!existsSync(file)) return false;
    const info = lstatSync(file);
    return info.isFile() && !info.isSymbolicLink() && info.nlink === 1 && info.size <= 20 * 1024 * 1024;
  })]);
}
const same = (a: unknown, b: unknown) => canonical(a) === canonical(b);
function compilerOutputs(root: string, state: State): string[] {
  return state.plan!.checks.flatMap(check => compilerOutputsFor(root, check));
}
function compilerOutputsFor(root: string, check: { command: string[] }): string[] {
  if (!/(?:^|[\\/])(?:gcc|g\+\+|clang|clang\+\+|cc|c\+\+)(?:\.exe)?$/i.test(check.command[0]!)) return [];
  const index = check.command.indexOf('-o');
  if (index < 0 || !check.command[index + 1]) return [];
  try { return projectPaths(root, [check.command[index + 1]!]); } catch { return []; }
}
function sourceMembership(root: string, state: State, row?: MonitorRow): string[] {
  if (row?.membership) return row.membership;
  const parents = state.plan!.outputs.map(path => dirname(path).replaceAll('\\', '/')).filter(path => path !== '.');
  const files = nativeContextFiles(root, [...new Set([...state.context, ...parents])], true, [...state.plan!.outputs, ...compilerOutputs(root, state)]);
  if (row) row.membership = files;
  return files;
}
function currentMembership(root: string, state: State, expected = state.context_membership, row?: MonitorRow): boolean {
  return !expected || same(sourceMembership(root, state, row), expected);
}
function matching(root: string, state: State, baseline?: Fingerprints, row?: MonitorRow): boolean {
  return !!state.plan && !!baseline && inputMapsMatch(root, state, fingerprints(root, Object.keys(baseline), row), baseline);
}
