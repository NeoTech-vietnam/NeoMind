function inputMapsMatch(root: string, state: State, actual?: Fingerprints, expected?: Fingerprints): boolean {
  return nativeSkillInputsMatch(root, selectedSkills(state), actual, expected, ordinarySkillReceipts(root, state));
}
function checkInputs(root: string, state: State, row?: MonitorRow): Fingerprints {
  if (row?.inputs) return row.inputs;
  const keyOf = (path: string) => process.platform === 'win32' ? path.toLowerCase() : path;
  const paths = new Set([...state.plan!.outputs, ...sourceMembership(root, state, row), ...ordinarySkillReceipts(root, state),
    ...Object.keys(nativeSkillPins(selectedSkills(state)))]), generated = new Set(compilerOutputs(root, state).map(keyOf));
  for (const check of state.plan!.checks) for (const [index, argument] of check.command.entries()) {
    if (/^-/.test(argument) || /[\x00-\x1f]/.test(argument)) continue;
    if (['-e', '--eval', '-c', '-command', '-encodedcommand', '--command'].includes(check.command[index - 1]?.toLowerCase() ?? '')) continue;
    try {
      const key = relative(resolve(root), isAbsolute(argument) ? resolve(argument) : safePath(root, argument)).replaceAll('\\', '/');
      if (generated.has(keyOf(key))) continue;
      const file = safePath(root, key);
      const explicitPath = argument.length <= 1024 && !/[;{}()[\]="'<>|&!?*]/.test(argument) &&
        (isAbsolute(argument) || /[\\/]|\.[a-z0-9_-]{1,12}$/i.test(argument));
      if (existsSync(file) ? lstatSync(file).isFile() : explicitPath) paths.add(key);
    } catch { /* Not an ordinary project-file argument. */ }
  }
  // Existing package scripts are an input even when the plan uses npm test.
  if (state.plan!.checks.some(check => /(?:^|[\\/])(?:npm|npx|pnpm|yarn|bun)(?:\.cmd)?$/i.test(check.command[0]!)))
    for (const path of ['package.json', 'package-lock.json', 'npm-shrinkwrap.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lock', 'bun.lockb'])
      if (existsSync(safePath(root, path))) paths.add(path);
  const inputs = fingerprints(root, [...paths], row);
  if (row) row.inputs = inputs;
  return inputs;
}
function inspectionsCurrent(root: string, state: State): boolean {
  const inputs = checkInputs(root, state);
  return (['WF.Reviewer', 'WF.Tester'] as const).every(role => {
    const job = state.assignments.findLast(item => item.agentName === role);
    return job?.state === 'completed' && inputMapsMatch(root, state, inputs, job.baseline) && currentMembership(root, state, job.context_membership);
  });
}
/** A current actual inspection with findings is evidence to diagnose, not a
 * passing verdict. This predicate is used only by host-owned diagnostic checks. */
function testerFindingsCurrent(root: string, state: State): boolean {
  if (!state.plan || state.interruption || ['accepted', 'cancelled'].includes(state.status)) return false;
  const inputs = checkInputs(root, state), jobs = (['WF.FnD', 'WF.Reviewer', 'WF.Tester'] as const)
    .map(role => state.assignments.findLast(job => job.agentName === role));
  if (jobs.some(job => !job?.report || job.adapter_error || job.invocation?.status !== 'returned' ||
      !matching(root, state, job.baseline) || !currentMembership(root, state, job.context_membership))) return false;
  const [implementation, reviewer, tester] = jobs;
  return new Set(jobs.map(job => job!.invocation!.host_call_id)).size === 3 &&
    [implementation, reviewer].every(job => job!.state === 'completed' && job!.report!.verdict === 'pass' && !job!.report!.findings.length) &&
    tester!.state === 'findings' && tester!.report!.verdict === 'findings' && tester!.report!.findings.length > 0 &&
    inputMapsMatch(root, state, inputs, reviewer!.baseline) && inputMapsMatch(root, state, inputs, tester!.baseline) && currentMembership(root, state) &&
    (!state.preservation_baseline || matching(root, state, state.preservation_baseline));
}
function diagnosticInspectionCurrent(root: string, state: State): boolean {
  return state.tester_evidence?.status === 'checking' && testerFindingsCurrent(root, state) &&
    state.assignments.findLast(job => job.agentName === 'WF.Tester')?.assignment_ref === state.tester_evidence.tester_assignment_ref &&
    state.tester_evidence.input_epoch === testerInputEpoch(root, state);
}
function testerInputEpoch(root: string, state: State): string {
  return hash(canonical({ plan_hash: state.plan_hash, inputs: checkInputs(root, state), membership: sourceMembership(root, state) }));
}
function checksCurrentAndPassed(root: string, state: State): boolean {
  return state.checks.length > 0 && generatedEvidenceCurrent(root, state) &&
    state.checks.every(check => check.state === 'passed' && !!check.evidence_id && !!check.result &&
      check.result.exit_code === 0 && !check.result.error && !check.result.cancelled && !check.result.timed_out &&
      !check.result.output_limited && checkCurrent(root, state, check));
}
function testerEvidenceEpoch(state: State, inputEpoch: string): string {
  return hash(canonical({ input_epoch: inputEpoch, generated_hashes: state.generated_hashes,
    checks: state.checks.map(check => ({ execution_id: check.execution_id, baseline: check.baseline, generated_inputs: check.generated_inputs,
      generated_outputs: check.generated_outputs, log_sha256: check.log_sha256 })) }));
}
function knownGeneratedCurrent(root: string, state: State, row?: MonitorRow): boolean {
  try { return matching(root, state, state.generated_hashes ?? {}, row); } catch { return false; }
}
function generatedEvidenceCurrent(root: string, state: State, row?: MonitorRow): boolean {
  return knownGeneratedCurrent(root, state, row) && compilerOutputs(root, state).every(path => typeof state.generated_hashes?.[path] === 'string');
}
function checkCurrent(root: string, state: State, check: Check, row?: MonitorRow): boolean {
  return inputMapsMatch(root, state, checkInputs(root, state, row), check.baseline) && currentMembership(root, state, undefined, row) &&
    matching(root, state, check.generated_inputs ?? {}, row) && matching(root, state, check.generated_outputs ?? {}, row) &&
    compilerOutputsFor(root, check).every(path => typeof check.generated_outputs?.[path] === 'string') && logCurrent(root, check, row);
}
function record(root: string, state: State, key: string, type: RecordType, title: string, body: string, extra: Record<string, unknown> = {}): ProjectRecord {
  const canonicalBody = (value: string) => value.replaceAll('\r\n', '\n').trim() + '\n';
  const content = { type, title, body: canonicalBody(body), data: extra };
  const contentHash = hash(canonical(content));
  // Reconcile a record committed just before a lost state-write response.
  const prior = loadRecords(root).find(item => item.meta.data.workflow_id === state.request_ref && item.meta.data.native_operation === key);
  if (prior) {
    const recorded = { type: prior.meta.type, title: prior.meta.title, body: canonicalBody(prior.body),
      data: Object.fromEntries(Object.keys(extra).map(field => [field, prior.meta.data[field]])) };
    if (prior.meta.data.native_content_hash !== contentHash || hash(canonical(recorded)) !== contentHash)
      fail('A saved native operation already contains different content; its records were not reused or overwritten.');
    if (!state.record_ids.includes(prior.meta.id)) state.record_ids.push(prior.meta.id);
    return prior;
  }
  const links: Link[] = [{ type: 'documents', target: state.request_ref }];
  if (typeof extra.requirement_id === 'string') links.push({ type: type === 'task' ? 'satisfies' : 'derives-from', target: extra.requirement_id });
  if (typeof extra.design_id === 'string') links.push({ type: 'implements', target: extra.design_id });
  if (typeof extra.task_id === 'string') links.push({ type: type === 'review' ? 'reviews' : type === 'check' ? 'verifies' : 'documents', target: extra.task_id });
  if (typeof extra.check_id === 'string') links.push({ type: 'evidence-for', target: extra.check_id });
  const created = createRecord(root, { type, title, body, owner: 'manager', links,
    data: { workflow_id: state.request_ref, process_contract: nativeRequestContract, native_operation: key,
      native_content_hash: contentHash, assurance, ...extra } });
  state.record_ids.push(created.meta.id);
  return created;
}
function view(root: string, state: State, row?: MonitorRow) {
  const current = state.plan ? fingerprints(root, state.plan.outputs, row) : {};
  const accepted = state.status === 'accepted' && !!state.accepted_hashes && same(current, state.accepted_hashes) && currentMembership(root, state, undefined, row) &&
    generatedEvidenceCurrent(root, state, row) && state.checks.every(check => checkCurrent(root, state, check, row)) && selectedSkillsCurrent(root, state);
  return { ...structuredClone(state), transport: 'vscode-native' as const, assurance,
    status: state.status === 'accepted' && !accepted ? 'changed' as const : state.status,
    historical_status: state.status, accepted, artifacts: Object.entries(current).map(([path, sha256]) => ({ path, sha256, exists: sha256 !== null })) };
}
function logCurrent(root: string, check: Check, row?: MonitorRow): boolean {
  if (!check.log_path || !check.log_sha256) return false;
  try { return fingerprints(root, [check.log_path], row)[check.log_path] === check.log_sha256; } catch { return false; }
}

export function openNativeRequest(root: string, input: NativeRequestOpenInput) {
  const parsed = nativeRequestOpenSchema.parse(input);
  const { requirement } = parsed, title = parsed.title ?? requirement.slice(0, 120);
  const context = projectPaths(root, parsed.context, true);
  const created = createRecord(root, { type: 'knowledge', title, body: `# ${title}\n\n${requirement}\n`,
    data: { kind: 'workforce-request', process_contract: nativeRequestContract, transport: 'vscode-native', assurance,
      routing_required: false, request_id: randomUUID() } });
  const folder = requestFolderForWorkflow(root, created.meta.id)!;
  const state: State = { schema_version: 1, process_contract: nativeRequestContract, request_ref: created.meta.id,
    request_key: folder.display_id, requirement, title, context, revision: 1, status: 'planning', updated_at: now(),
    record_ids: [], assignments: [], checks: [] };
  save(root, state);
  return view(root, state);
}

export function getNativeRequest(root: string, requestRef: string) { return view(root, load(root, requestRef)); }

