export function nativeRequestListForMonitor(root: string, ownership: NativeMonitorOwnership = {}, snapshot = new NativeMonitorSnapshot(root)) {
  if (!existsSync(safePath(root, '.neomind/config.json'))) return [];
  snapshot.assertRoot(root);
  return snapshot.records().filter(item => item.meta.data.kind === 'workforce-request' && item.meta.data.delivery_scope !== 'role-only' &&
    item.meta.data.process_contract === nativeRequestContract).map(item => {
    const folder = requestFolderForWorkflow(root, item.meta.id);
    try {
      const row: MonitorRow = { files: snapshot };
      const state = load(root, item.meta.id, item), current = view(root, state, row);
      const calls = (ownership.calls ?? []).filter(call => call.request_ref === state.request_ref &&
        state.assignments.some(job => job.assignment_ref === call.assignment_ref && job.agentName === call.agentName && job.state === 'issued'));
      const queued = (ownership.queued_calls ?? []).filter(call => call.request_ref === state.request_ref &&
        state.assignments.some(job => job.assignment_ref === call.assignment_ref && job.agentName === call.agentName && job.state === 'issued'));
      const checkOwner = ownership.check_requests?.includes(state.request_ref) === true;
      const live = calls.length > 0 || queued.length > 0 || checkOwner;
      function roleStage(role: Role) {
        const job = state.assignments.findLast(job => job.agentName === role);
        if (!job) return 'pending';
        if (job.state === 'issued') return calls.some(call => call.assignment_ref === job.assignment_ref) ? job.escalation ? 'repairing' : 'running'
          : queued.some(call => call.assignment_ref === job.assignment_ref) ? 'queued' : 'uncertain';
        if (job.state === 'completed') return matching(root, state, job.baseline, row) && currentMembership(root, state, job.context_membership, row) ? 'completed' : 'uncertain';
        return job.state === 'findings' ? 'failed' : job.state === 'cancelled' ? 'interrupted' : 'uncertain';
      }
      const stages = [
        { id: 'requirements', role: 'WF.PM', state: state.plan ? 'completed' : 'pending', rationale: 'Requirements saved by the native parent plan; no separate SWSD invocation is implied.' },
        { id: 'analysis', role: 'WF.PM', state: state.plan ? 'completed' : 'pending', rationale: 'Scope and acceptance criteria supplied in the saved plan.' },
        { id: 'architecture', role: 'WF.PM', state: state.plan ? 'completed' : 'pending', rationale: 'Applicable design supplied in the saved plan; no separate P-RES invocation is implied.' },
        { id: 'module-design', role: 'WF.PM', state: state.plan ? 'completed' : 'pending', rationale: 'Module decisions belong to the saved design.' },
        { id: 'coding', role: 'WF.FnD', state: roleStage('WF.FnD') },
        ...(['unit', 'integration', 'system', 'acceptance'] as const).map(level => {
          const allocated = state.checks.filter(check => check.level === level);
          const stateOf = (check: Check) => check.state === 'running' ? checkOwner ? 'running' : 'uncertain'
            : check.state === 'passed' ? checkCurrent(root, state, check, row) ? 'completed' : 'uncertain'
            : check.state === 'failed' ? 'failed' : check.state === 'uncertain' ? 'uncertain' : 'pending';
          const values = allocated.map(stateOf);
          const status = !values.length ? 'not-applicable' : ['running', 'uncertain', 'failed'].find(value => values.some(current => current === value)) ??
            (values.every(value => value === 'completed') ? 'completed' : 'pending');
          return { id: level, role: 'WF.Tester', state: status,
            rationale: !allocated.length ? 'No command at this verification level was allocated by the saved plan.' :
              allocated.map(check => `${check.title}: ${stateOf(check)}${check.result ? ` (exit ${check.result.exit_code})` : ''}`).join('; ') };
        }),
      ];
      return { workflow_id: state.request_ref, request_key: state.request_key, title: state.title, revision: state.revision,
        updated_at: state.updated_at, status: state.status === 'working' && !live ? 'uncertain' : current.status,
        accepted: current.accepted, transport: 'vscode-native', source: 'native-local', live,
        current_action: current.accepted ? 'Current products accepted after independent native review and actual checks.' :
          calls.length ? `${calls.map(call => call.agentName).join(', ')} running in native Local chat.` :
          queued.length ? `${queued.map(call => call.agentName).join(', ')} queued for an available native worker slot.` :
          checkOwner ? 'Running the saved verification commands.' : state.status === 'working' ? 'No current editor-owned execution is observed.' : 'Saved native results; current products and check evidence are retained.',
        stages, review: { role: 'WF.Reviewer', state: roleStage('WF.Reviewer') },
        active_agents: calls.map(call => ({ role: call.agentName, state: 'running', requested_model: call.requested_model ?? { selection: 'inherit' },
          observed_model: 'unknown', observed_provider: 'unknown' })),
        artifacts: current.artifacts.map(file => ({ path: file.path, exists: file.exists, state: current.accepted ? 'accepted' : 'unverified' })),
        evidence: state.checks.filter(check => check.log_path).map(check => ({ path: check.log_path!, label: check.title,
          ...(check.result ? { exit_code: check.result.exit_code } : {}),
          passed: check.state === 'passed' && checkCurrent(root, state, check, row) })),
        folder: folder ? `.workforce/${folder.directory}` : undefined };
    } catch {
      return { workflow_id: item.meta.id, request_key: folder?.display_id ?? item.meta.id, title: item.meta.title,
        status: 'uncertain', current_action: 'Saved native evidence could not be read. Existing execution was not restarted.',
        source: 'native-local', transport: 'vscode-native', stages: [], artifacts: [], evidence: [], active_agents: [], accepted: false };
    }
  });
}

export function planNativeRequest(root: string, requestRef: string, input: NativeRequestPlan) {
  const parsed = nativePlanSchema.parse(input);
  const plan = { ...parsed, outputs: projectPaths(root, parsed.outputs) };
  plan.outputs.forEach(path => safePath(root, path));
  if (plan.outputs.some(path => /[\\\x00-\x1f]/.test(path) || path.split('/').some(part => !part || part === '.' || part === '..')))
    fail('Plan products require canonical relative file paths.');
  if (plan.outputs.some(path => /^(?:\.git|\.workforce|\.neomind|\.verythinker|\.taskforces)(?:\/|$)/i.test(path)))
    fail('Plan product destinations must be outside managed execution and Git metadata.');
  if (plan.checks.some(check => check.command.some(argument => argument.includes('\0')))) fail('Check arguments cannot contain NUL.');
  return locked(root, requestRef, state => {
    const digest = hash(canonical(plan));
    if (state.plan_hash) {
      if (state.plan_hash === digest) return view(root, state);
      fail('The saved plan is immutable. Preserve it and open a linked increment for a changed plan.');
    }
    const selected = resolveNativeSkills(root, [...new Set(Object.values(plan.role_skills ?? {}).flatMap(names => names ?? []))]);
    const contexts = Object.fromEntries(Object.entries(plan.role_skills ?? {}).map(([role, names]) =>
      [role, (names ?? []).map(name => selected.find(item => item.name === name)!)]));
    state.plan = plan; state.plan_hash = digest;
    if (selected.length) state.skill_contexts = contexts;
    state.reuse = prepareNativeWork(root, { requirement: state.requirement, task_family: plan.task_family,
      parameters: plan.parameters ?? {}, outputs: plan.outputs });
    state.preservation_baseline = { ...preservationBaseline(root, state), ...nativeSkillPins(selected) };
    state.context_membership = sourceMembership(root, state);
    const requirements = record(root, state, 'requirements', 'requirement', `${state.title}: requirements`,
      plan.requirements.map((text, index) => `${index + 1}. ${text}`).join('\n'));
    const design = record(root, state, 'design', 'design', `${state.title}: design`, plan.design,
      { requirement_id: requirements.meta.id });
    const task = record(root, state, 'task', 'task', `${state.title}: implementation`, plan.summary,
      { requirement_id: requirements.meta.id, design_id: design.meta.id, output_paths: plan.outputs });
    state.task_id = task.meta.id;
    state.checks = plan.checks.map((check, index) => {
      const saved = record(root, state, `check-${index}`, 'check', check.title,
        `Level: ${check.level}\n\nCommand argv:\n\n${JSON.stringify(check.command)}\n`, { task_id: task.meta.id });
      return { ...check, record_id: saved.meta.id, state: 'pending' };
    });
    state.status = 'working'; save(root, state);
    return view(root, state);
  });
}

export interface NativeReportArtifact { path: string; content: string }
export function parseNativeProfessionalReport(raw: unknown, options: { report_artifacts?: boolean } = {}): {
  report?: ProfessionalReport; text: string; report_artifacts?: NativeReportArtifact[];
} {
  const text = typeof raw === 'string' ? raw : Array.isArray((raw as { content?: unknown[] })?.content)
    ? (raw as { content: Array<{ value?: unknown; text?: unknown }> }).content.map(part => typeof part.value === 'string' ? part.value : typeof part.text === 'string' ? part.text : '').join('\n') : '';
  if (text.length > 128 * 1024) return { text: text.slice(0, 128 * 1024) };
  const values = new Set([text.trim(), ...[...text.matchAll(/```(?:json)?\s*([\s\S]*?)```/g)].map(match => match[1]!.trim())]);
  // Native text parts can concatenate a short explanation with the JSON report.
  // Extract balanced objects in one bounded pass, including escaped strings;
  // never use a greedy brace regex or ask another model to repair formatting.
  const openings: { start: number; summary: boolean; verdict: boolean }[] = [];
  let quoted = false, escaped = false, stringStart = 0, candidateBytes = 0;
  for (let index = 0; index < text.length; index++) {
    const character = text[index];
    if (quoted) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') {
        quoted = false;
        const key = text.slice(stringStart + 1, index), current = openings.at(-1);
        let next = index + 1; while (/\s/.test(text[next] ?? '') && next < text.length) next++;
        if (current && text[next] === ':' && (key === 'summary' || key === 'verdict')) current[key] = true;
      }
    } else if (character === '"' && openings.length) { quoted = true; stringStart = index; }
    else if (character === '{') openings.push({ start: index, summary: false, verdict: false });
    else if (character === '}') {
      const current = openings.pop();
      if (current?.summary && current.verdict) {
        candidateBytes += index + 1 - current.start;
        if (candidateBytes > text.length * 4) return { text };
        values.add(text.slice(current.start, index + 1));
      }
    }
  }
  const reports = new Map<string, { report: ProfessionalReport; report_artifacts?: NativeReportArtifact[] }>();
  let invalidArtifacts = false;
  for (const value of values) {
    try {
      const decoded = JSON.parse(value);
      // Identity/lifecycle claims in model prose are not backend authority.
      const parsed = nativeReportSchema.safeParse({ summary: decoded?.summary, verdict: decoded?.verdict, findings: decoded?.findings });
      if (parsed.success) {
        let report_artifacts: NativeReportArtifact[] | undefined;
        if (options.report_artifacts && decoded.report_artifacts !== undefined) {
          const supplied = decoded.report_artifacts;
          if (!Array.isArray(supplied) || supplied.length > 100 || supplied.some(item => !item || typeof item !== 'object' || Array.isArray(item) ||
              Object.keys(item).some(key => !['path', 'content'].includes(key)) || typeof item.path !== 'string' || !item.path.trim() || item.path.length > 1024 ||
              typeof item.content !== 'string' || !item.content.length || item.content.length > 128 * 1024)) { invalidArtifacts = true; continue; }
          report_artifacts = supplied.map(item => ({ path: item.path, content: item.content }));
        }
        const entry = { report: parsed.data, ...(report_artifacts ? { report_artifacts } : {}) };
        reports.set(canonical(options.report_artifacts ? entry : parsed.data), entry);
      }
    } catch { /* Retain an incomplete professional report without submitting it. */ }
  }
  // Conflicting valid objects are ambiguous, not authority to select a pass.
  return !invalidArtifacts && reports.size === 1 ? { ...reports.values().next().value!, text } : { text };
}

