/** Runs an eligible exact procedure once before the first native implementation.
 * Its backend-issued request reference is also the runner's idempotency key. */
export async function prepareNativeImplementation(root: string, requestRef: string, options: { signal?: AbortSignal } = {}) {
  const input = locked(root, requestRef, state => {
    if (state.status !== 'working' || state.interruption || !state.plan || state.assignments.length || state.reuse_execution ||
        !state.reuse || !['qualified-procedure', 'adapt'].includes(state.reuse.strategy) || !('procedure' in state.reuse) || !state.reuse.procedure) return;
    state.reuse_execution = { status: 'running' }; save(root, state);
    return { request_ref: state.request_ref, requirement: state.requirement, task_family: state.plan.task_family,
      parameters: state.plan.parameters ?? {}, outputs: state.plan.outputs, procedure: state.reuse.procedure };
  });
  if (!input) return getNativeRequest(root, requestRef);
  const outcome = await executePreparedNativeProcedure(root, input, options);
  return locked(root, requestRef, state => {
    state.reuse_execution = outcome;
    record(root, state, 'qualified-procedure', 'knowledge', `${state.title}: existing procedure execution`,
      `Host procedure outcome: ${JSON.stringify(outcome, null, 2)}\n\nThis is actual local execution evidence, not whole-product acceptance.`,
      { task_id: state.task_id, procedure_execution: outcome });
    save(root, state); return view(root, state);
  });
}

/** Explicit host continuation after a corrected contract/environment. Retain
 * old reports and current products; never rewrite a failed callback as pass. */
export function resumeNativeRequest(root: string, requestRef: string) {
  const reconciled = reconcileNativeCheckReceipts(root, requestRef);
  if (reconciled) return reconciled;
  return continueNativeRequest(root, requestRef, false);
}

/** Automatic continuation is a host decision, never another model lifecycle
 * call. Provider/preflight rejection and cancellation are not product retries. */
export function prepareNativeRepair(root: string, requestRef: string) {
  return continueNativeRequest(root, requestRef, true);
}

/** Host-only reconciliation of a genuinely changed input epoch. Provider,
 * authentication, malformed reports and unknown in-flight effects are not
 * retried here. No old report or check is rewritten as current evidence. */
export function reconcileNativeInputChange(root: string, requestRef: string) {
  return locked(root, requestRef, state => {
    const result = (outcome: 'prepared' | 'unchanged' | 'exhausted', code: string, message: string) =>
      ({ state: view(root, state), outcome, code, message });
    const none = () => result('unchanged', 'INPUTS_NOT_RECONCILABLE', 'No completed changed-input inspection can be reconciled automatically.');
    const last = state.assignments.at(-1), implementation = state.assignments.findLast(job => job.agentName === 'WF.FnD');
    if (!state.plan || state.interruption || ['accepted', 'cancelled'].includes(state.status) || !last?.report || last.adapter_error ||
        last.invocation?.status !== 'returned' || last.state === 'issued' ||
        state.checks.some(check => check.execution_id && !check.result || check.result?.cancelled) ||
        !implementation || implementation.state !== 'completed' || implementation.invocation?.status !== 'returned' ||
        !matching(root, state, implementation.baseline) || state.preservation_baseline && !matching(root, state, state.preservation_baseline)) return none();
    const inputs = checkInputs(root, state), membership = sourceMembership(root, state);
    // The input epoch is a filesystem observation, not the mutable checkpoint
    // map that this preparation resets before running the compiler again.
    const generatedKeys = [...new Set([...compilerOutputs(root, state), ...Object.keys(state.generated_hashes ?? {})])];
    const generated = fingerprints(root, generatedKeys);
    const epoch = hash(canonical({ inputs, membership, generated }));
    if (state.input_reconciliation?.epoch === epoch && state.input_reconciliation.status === 'prepared' &&
        state.input_reconciliation.assignment_ref === last.assignment_ref && state.status === 'working' &&
        (state.resume_role || state.resume_checks))
      return result('prepared', state.input_reconciliation.code, state.input_reconciliation.message);
    const inspections = (['WF.Reviewer', 'WF.Tester'] as const).map(role => state.assignments.findLast(job => job.agentName === role));
    const stale = inspections.find(job => job?.report && !job.adapter_error && job.invocation?.status === 'returned' &&
      job.baseline && job.context_membership && (!inputMapsMatch(root, state, inputs, job.baseline) || !same(membership, job.context_membership)));
    const changedCheck = state.checks.find(check => check.baseline && !inputMapsMatch(root, state, inputs, check.baseline));
    const membershipChanged = !same(membership, state.context_membership);
    const generatedChanged = !matching(root, state, state.generated_hashes ?? {});
    const pendingEpochChanged = state.input_reconciliation?.status === 'prepared' &&
      state.input_reconciliation.assignment_ref === last.assignment_ref && state.input_reconciliation.epoch !== epoch && state.resume_checks;
    if (!stale && !changedCheck && !membershipChanged && !generatedChanged && !pendingEpochChanged) return none();
    // Fresh checks alone are allowed only when both actual inspections still
    // cover the exact current source/checker revision.
    if (!stale && !inspectionsCurrent(root, state)) return none();
    const before = stale?.baseline ?? changedCheck?.baseline ?? {}, beforeMembership = stale?.context_membership ?? state.context_membership ?? [];
    const changedPaths = [...new Set([...Object.keys(before), ...Object.keys(inputs), ...beforeMembership, ...membership,
      ...Object.keys(generated)].filter(path => before[path] !== inputs[path] ||
        beforeMembership.includes(path) !== membership.includes(path) || generated[path] !== state.generated_hashes?.[path]))].sort().slice(0, 100);
    const repeated = state.input_reconciliation_epochs?.includes(epoch);
    const exhausted = (state.repair_attempts ?? 0) >= readConfig(root).repair_attempts;
    if (repeated || exhausted) {
      const code = repeated ? 'INPUT_EPOCH_ALREADY_RECONCILED' : 'INPUT_RECONCILIATION_BUDGET';
      const message = repeated ? 'This exact input revision already used a reconciliation; no identical inspection loop was started.'
        : 'The configured repair allowance is exhausted after input changes; retained reports and actual checks remain available.';
      state.input_reconciliation = { epoch, assignment_ref: last.assignment_ref, status: 'exhausted', code, message, changed_paths: changedPaths };
      state.status = 'uncertain';
      record(root, state, `input-reconciliation-stop-${code}-${epoch}`, 'knowledge', `${state.title}: input reconciliation stopped`, message,
        { input_epoch: epoch, reason_code: code });
      save(root, state); return result('exhausted', code, message);
    }
    const message = stale ? `Source/checker inputs changed; fresh ${stale.agentName} inspection and subsequent verification are required.`
      : 'Inputs changed after inspection/check execution; current inspections are retained and actual checks will run on the new epoch.';
    state.input_reconciliation_epochs = [...(state.input_reconciliation_epochs ?? []), epoch];
    state.input_reconciliation = { epoch, assignment_ref: last.assignment_ref, status: 'prepared',
      code: 'INPUT_REVISION_RECONCILED', message, changed_paths: changedPaths };
    state.repair_attempts = (state.repair_attempts ?? 0) + 1;
    if (state.checks.some(check => check.execution_id)) {
      state.check_history ??= [];
      state.check_history.push(...structuredClone(state.checks));
      state.checks = state.plan.checks.map((check, index) => {
        const saved = record(root, state, `input-recheck-${epoch}-${index}`, 'check', check.title,
          `Level: ${check.level}\n\nCommand argv:\n\n${JSON.stringify(check.command)}\n`, { task_id: state.task_id });
        return { ...check, record_id: saved.meta.id, state: 'pending' };
      });
    } else state.checks = state.checks.map(check => ({ ...check, state: 'pending' }));
    state.generated_hashes = {};
    state.context_membership = membership;
    delete state.repair_context; delete state.escalate_next;
    if (stale) { state.resume_role = stale.agentName; delete state.resume_checks; }
    else { state.resume_checks = true; delete state.resume_role; }
    state.status = 'working';
    record(root, state, `input-reconciliation-${epoch}`, 'knowledge', `${state.title}: fresh input inspection`, message,
      { input_epoch: epoch, changed_paths: changedPaths, resume_role: stale?.agentName ?? null, repair_attempt: state.repair_attempts });
    save(root, state); return result('prepared', 'INPUT_REVISION_RECONCILED', message);
  });
}

type TesterEvidenceResult = { state: ReturnType<typeof view>; outcome: 'tester' | 'failed' | 'unchanged' | 'uncertain'; code: string; message: string };
const evidenceReassessments = new Map<string, Promise<TesterEvidenceResult>>();
/** One evidence-first host operation; never a model-facing lifecycle tool. */
export function reassessNativeTesterFindings(root: string, requestRef: string, options: { signal?: AbortSignal } = {}): Promise<TesterEvidenceResult> {
  const key = `${process.platform === 'win32' ? resolve(root).toLowerCase() : resolve(root)}:${requestRef}`;
  const owned = evidenceReassessments.get(key);
  if (owned) return owned;
  const operation = performTesterReassessment(root, requestRef, options).finally(() => {
    if (evidenceReassessments.get(key) === operation) evidenceReassessments.delete(key);
  });
  evidenceReassessments.set(key, operation); return operation;
}
async function performTesterReassessment(root: string, requestRef: string, options: { signal?: AbortSignal }): Promise<TesterEvidenceResult> {
  const prepare = locked(root, requestRef, state => {
    const result = (outcome: TesterEvidenceResult['outcome'], code: string, message: string): TesterEvidenceResult => ({ state: view(root, state), outcome, code, message });
    if (!testerFindingsCurrent(root, state) || options.signal?.aborted)
      return { result: result('unchanged', 'TESTER_EVIDENCE_NOT_ELIGIBLE', 'No current owned Tester finding is eligible for host reassessment.') };
    const epoch = testerInputEpoch(root, state), tester = state.assignments.findLast(job => job.agentName === 'WF.Tester')!;
    const unknown = state.checks.filter(check => check.execution_id && !check.result);
    if (unknown.length) {
      const executions = unknown.map(check => check.execution_id!);
      for (const check of unknown) check.state = 'uncertain';
      state.status = 'uncertain';
      if (state.tester_evidence) state.tester_evidence.status = 'uncertain';
      record(root, state, `diagnostic-unknown-${hash(canonical(executions))}`, 'knowledge', `${state.title}: check effects unconfirmed`,
        'A committed check has no observed process outcome. Its identity and prior evidence were retained; no command or model was repeated.',
        { execution_ids: executions });
      save(root, state);
      return { result: result('uncertain', 'CHECK_EFFECTS_UNCONFIRMED', 'A prior committed check still has unconfirmed effects; it was not repeated.') };
    }
    if (state.tester_evidence?.input_epoch === epoch && state.tester_evidence.status === 'tester-pending' &&
        !state.tester_evidence.reassessment_assignment_ref && checksCurrentAndPassed(root, state))
      return { result: result('tester', 'HOST_EVIDENCE_READY', 'Current host evidence is retained for one fresh Tester verdict.') };
    const continuing = state.tester_evidence?.input_epoch === epoch && state.tester_evidence.status === 'checking' &&
      state.tester_evidence.tester_assignment_ref === tester.assignment_ref;
    const existingEvidence = checksCurrentAndPassed(root, state) ? testerEvidenceEpoch(state, epoch) : undefined;
    const diagnosed = state.tester_diagnostic_input_epochs?.includes(epoch);
    if (!continuing && diagnosed && (!existingEvidence || state.tester_evidence_epochs?.includes(existingEvidence)))
      return { result: result('unchanged', 'EVIDENCE_EPOCH_ALREADY_REASSESSED', 'This exact input/evidence revision already received its bounded Tester reassessment.') };
    if (!continuing) {
      if (!diagnosed) state.tester_diagnostic_input_epochs = [...(state.tester_diagnostic_input_epochs ?? []), epoch];
      state.tester_evidence = { input_epoch: epoch, tester_assignment_ref: tester.assignment_ref, status: 'checking' };
      if (state.checks.some(check => check.execution_id) && !checksCurrentAndPassed(root, state)) {
        state.check_history ??= []; state.check_history.push(...structuredClone(state.checks));
        state.checks = state.plan!.checks.map((check, index) => {
          const saved = record(root, state, `diagnostic-check-${epoch}-${index}`, 'check', check.title,
            `Level: ${check.level}\n\nCommand argv:\n\n${JSON.stringify(check.command)}\n`, { task_id: state.task_id });
          return { ...check, record_id: saved.meta.id, state: 'pending' };
        });
        state.generated_hashes = {};
      }
      record(root, state, `tester-diagnostic-${epoch}-${existingEvidence ?? 'run'}`, 'knowledge', `${state.title}: committed host diagnostics`,
        'Run the existing committed checks against current owned implementation and review. Tester findings remain unresolved until a fresh actual Tester verdict.',
        { input_epoch: epoch, tester_assignment_ref: tester.assignment_ref });
      save(root, state);
    }
    return { epoch };
  });
  if (prepare.result) return prepare.result;
  try { await runNativeChecks(root, requestRef, { ...options, purpose: 'tester-diagnostic' }); }
  catch (error) {
    if (!(error instanceof Error) || (error as Error & { code?: string }).code !== 'NATIVE_INPUT_REVISION_CHANGED') throw error;
  }
  return locked(root, requestRef, state => {
    const result = (outcome: TesterEvidenceResult['outcome'], code: string, message: string): TesterEvidenceResult => ({ state: view(root, state), outcome, code, message });
    if (state.interruption || options.signal?.aborted || !diagnosticInspectionCurrent(root, state)) {
      if (state.tester_evidence?.input_epoch === prepare.epoch) state.tester_evidence.status = 'uncertain';
      if (!state.interruption) state.status = options.signal?.aborted ? 'cancelled' : 'uncertain';
      save(root, state); return result('uncertain', 'HOST_DIAGNOSTIC_REVISION_UNCONFIRMED', 'Current diagnostic inputs or ownership changed; existing evidence and findings were retained.');
    }
    if (!checksCurrentAndPassed(root, state)) {
      state.tester_evidence!.status = state.checks.some(check => check.state === 'failed' && check.result) ? 'failed' : 'uncertain';
      state.status = state.tester_evidence!.status === 'failed' ? 'findings' : 'uncertain'; save(root, state);
      return result(state.tester_evidence!.status === 'failed' ? 'failed' : 'uncertain', 'HOST_DIAGNOSTIC_CHECKS_NOT_PASSED',
        'Actual committed host checks did not confirm this product; original Tester findings and process evidence remain.');
    }
    const evidenceEpoch = testerEvidenceEpoch(state, prepare.epoch!);
    if (state.tester_evidence_epochs?.includes(evidenceEpoch))
      return result('unchanged', 'EVIDENCE_EPOCH_ALREADY_REASSESSED', 'The same actual host evidence already received a Tester reassessment.');
    state.tester_evidence_epochs = [...(state.tester_evidence_epochs ?? []), evidenceEpoch];
    state.tester_evidence!.evidence_epoch = evidenceEpoch;
    state.tester_evidence!.status = 'tester-pending'; state.resume_role = 'WF.Tester'; state.escalate_next = true;
    delete state.resume_checks; delete state.repair_context; state.status = 'working';
    record(root, state, `tester-evidence-${evidenceEpoch}`, 'knowledge', `${state.title}: actual evidence for fresh Tester`,
      state.checks.map(check => `${check.title}: exit ${check.result!.exit_code}; ${check.log_path}`).join('\n') + '\n',
      { input_epoch: prepare.epoch, evidence_epoch: state.tester_evidence!.evidence_epoch });
    save(root, state); return result('tester', 'HOST_EVIDENCE_READY', 'Passing current host evidence is ready for a separate fresh Tester verdict; findings were not waived.');
  });
}

/** Explicit host continuation after correcting a check environment. Existing
 * independent inspections are reusable only while their exact inputs remain
 * unchanged. Product/checker edits still require the ordinary repair path. */
export function recheckNativeRequest(root: string, requestRef: string) {
  const reconciled = reconcileNativeCheckReceipts(root, requestRef);
  if (reconciled) return reconciled;
  return locked(root, requestRef, state => {
    if (recoverEditorInterruption(root, state, true)) return view(root, state);
    if (state.status === 'accepted' && view(root, state).accepted) return view(root, state);
    if (!state.plan || state.interruption || !['findings', 'uncertain', 'accepted'].includes(state.status) ||
        !state.checks.some(check => check.result) || state.checks.some(check => check.execution_id && !check.result))
      fail('Rechecking requires a retained failed command with known effects.');
    for (const role of ['WF.FnD', 'WF.Reviewer', 'WF.Tester'] as const) {
      const job = state.assignments.findLast(job => job.agentName === role);
      if (job?.state !== 'completed' || !matching(root, state, job.baseline) || !currentMembership(root, state, job.context_membership))
        fail('Changed or incomplete product inspection requires fresh independent roles before rechecking.');
    }
    if (!inspectionsCurrent(root, state)) fail('Changed or incomplete product inspection requires fresh independent roles before rechecking.');
    state.check_history ??= [];
    state.check_history.push(...structuredClone(state.checks));
    state.checks = state.plan.checks.map((check, index) => {
      const saved = record(root, state, `recheck-${randomUUID()}-${index}`, 'check', check.title,
        `Level: ${check.level}\n\nCommand argv:\n\n${JSON.stringify(check.command)}\n`, { task_id: state.task_id });
      return { ...check, record_id: saved.meta.id, state: 'pending' };
    });
    state.resume_checks = true; delete state.resume_role;
    state.generated_hashes = {};
    state.status = 'working'; save(root, state); return view(root, state);
  });
}

export function getNativeRequestByKey(root: string, requestKey: string) {
  const folder = requestFolderForDisplayId(root, requestKey);
  if (!folder) fail('This request key is not present in the selected workspace.');
  return getNativeRequest(root, folder.workflow_id);
}

/** A checkpoint is evidence of a settled host channel, not an inference that a
 * missing editor or process must have stopped. No model supplies this proof. */
function editorEffectsHash(root: string, state: State): string | undefined {
  try {
    if (!state.plan || state.plan_hash !== hash(canonical(state.plan)) || state.reuse_execution?.status === 'running') return;
    const records = new Map(loadRecords(root).map(saved => [saved.meta.id, saved]));
    const assignments = state.assignments.map(job => {
      if (job.state === 'issued' || !job.result_hash || !job.report_record_id) throw new Error('Unobserved invocation');
      const saved = records.get(job.report_record_id);
      if (!saved) throw new Error('Outcome record missing');
      const data = saved.meta.data;
      if (data.workflow_id !== state.request_ref || data.native_assignment_ref !== job.assignment_ref) throw new Error('Unbound outcome');
      if (job.invocation) {
        if (job.invocation.invoked !== true || !['returned', 'rejected', 'cancelled'].includes(job.invocation.status) ||
            !same(data.native_invocation, job.invocation)) throw new Error('Unconfirmed native end');
      } else if (data.invoked !== false || !data.dispatch_failure) throw new Error('Unconfirmed preflight');
      return { assignment_ref: job.assignment_ref, state: job.state, result_hash: job.result_hash,
        invocation: job.invocation ?? null, record_sha256: hash(readFileSync(safePath(root, saved.path))) };
    });
    const checks = state.checks.map(check => {
      if (!check.execution_id) return { record_id: check.record_id, state: check.state };
      if (!check.result || check.state === 'running' || !check.log_path || !check.log_sha256 ||
          fingerprints(root, [check.log_path])[check.log_path] !== check.log_sha256) throw new Error('Unknown check effects');
      if (check.result.exit_code === null && check.result.signal === null)
        throw new Error('Checker process close was not observed');
      return { record_id: check.record_id, execution_id: check.execution_id, state: check.state,
        result: check.result, log_path: check.log_path, log_sha256: check.log_sha256 };
    });
    return hash(canonical({ generation: state.editor_generation ?? 0, plan_hash: state.plan_hash, assignments, checks }));
  } catch { return; }
}

const editorRecoveryMessages = {
  EDITOR_EFFECTS_UNCONFIRMED: 'The prior editor did not retain a settled native outcome or drained checker checkpoint. Existing effects are uncertain; no work was replayed.',
  EDITOR_INPUTS_CHANGED: 'Source, products, checker inputs or selected guidance changed after the editor stopped. Retained work needs reconciliation; no evidence was reused or files overwritten.',
  EDITOR_CHECK_RECONCILIATION_REQUIRED: 'The interrupted checker has unresolved non-cancellation findings or stale independent inspections. No check or model was replayed.',
} as const;
function editorRecoveryFailure(root: string, state: State, code: keyof typeof editorRecoveryMessages): never {
  if (state.status !== 'uncertain') { state.status = 'uncertain'; save(root, state); }
  throw Object.assign(new Error(editorRecoveryMessages[code]), { code });
}
function assertEditorRecoveryInputs(root: string, state: State): void {
  const recovery = state.editor_recovery, interruption = state.interruption_history?.findLast(item => item.at === recovery?.interruption_at);
  const checkpoint = interruption?.editor_checkpoint;
  if (!recovery || !checkpoint || recovery.generation !== state.editor_generation || checkpoint.generation + 1 !== recovery.generation)
    editorRecoveryFailure(root, state, 'EDITOR_EFFECTS_UNCONFIRMED');
  if (!selectedSkillsCurrent(root, state) || !inputMapsMatch(root, state, checkInputs(root, state), checkpoint.inputs) ||
      !currentMembership(root, state, checkpoint.membership) ||
      state.preservation_baseline && !matching(root, state, state.preservation_baseline))
    editorRecoveryFailure(root, state, 'EDITOR_INPUTS_CHANGED');
}

/** Only explicit same-request recovery of an editor-owned, observed end. User
 * cancellation and unknown crash effects retain their original interruption. */
function recoverEditorInterruption(root: string, state: State, recheckOnly: boolean): boolean {
  const interruption = state.interruption;
  if (!interruption) {
    const prepared = state.status === 'working' && state.editor_recovery?.status === 'prepared' &&
      state.editor_recovery.generation === state.editor_generation && (state.resume_checks === true || state.resume_role !== undefined);
    if (prepared && recheckOnly && (state.editor_recovery!.mode !== 'checks' || !state.resume_checks))
      throw Object.assign(new Error(editorRecoveryMessages.EDITOR_CHECK_RECONCILIATION_REQUIRED), { code: 'EDITOR_CHECK_RECONCILIATION_REQUIRED' });
    if (prepared) assertEditorRecoveryInputs(root, state);
    return prepared;
  }
  if (interruption.code !== 'EDITOR_CLOSED' || interruption.category !== 'cancellation') return false;
  const checkpoint = interruption.editor_checkpoint;
  if (!checkpoint || checkpoint.generation !== (state.editor_generation ?? 0) ||
      checkpoint.effects_hash !== editorEffectsHash(root, state)) editorRecoveryFailure(root, state, 'EDITOR_EFFECTS_UNCONFIRMED');
  if (!selectedSkillsCurrent(root, state) || !inputMapsMatch(root, state, checkInputs(root, state), checkpoint.inputs) ||
      !currentMembership(root, state, checkpoint.membership) ||
      state.preservation_baseline && !matching(root, state, state.preservation_baseline))
    editorRecoveryFailure(root, state, 'EDITOR_INPUTS_CHANGED');
  const roles: Role[] = ['WF.FnD', 'WF.Reviewer', 'WF.Tester'];
  let unfinished: Role | undefined;
  for (const role of roles) {
    const job = state.assignments.findLast(item => item.agentName === role);
    if (job?.state === 'completed' && job.report?.verdict === 'pass' && !job.report.findings.length) {
      if (!matching(root, state, job.baseline) || !currentMembership(root, state, job.context_membership))
        editorRecoveryFailure(root, state, 'EDITOR_INPUTS_CHANGED');
    } else { unfinished = role; break; }
  }
  if (recheckOnly && unfinished) editorRecoveryFailure(root, state, 'EDITOR_CHECK_RECONCILIATION_REQUIRED');
  const passedCurrent = (check: Check) => check.state === 'passed' && !!check.evidence_id && !!check.result &&
    check.result.exit_code === 0 && !check.result.cancelled && !check.result.timed_out && !check.result.output_limited &&
    !check.result.error && checkCurrent(root, state, check);
  if (!unfinished && (!inspectionsCurrent(root, state) || state.checks.some(check => check.execution_id &&
      (!check.result?.cancelled && !passedCurrent(check)))))
    editorRecoveryFailure(root, state, 'EDITOR_CHECK_RECONCILIATION_REQUIRED');
  const generation = (state.editor_generation ?? 0) + 1;
  state.interruption_history ??= []; state.interruption_history.push(structuredClone(interruption));
  state.editor_generation = generation;
  state.editor_recovery = { generation, interruption_at: interruption.at, mode: unfinished ? 'roles' : 'checks', status: 'prepared' };
  if (unfinished) { state.resume_role = unfinished; delete state.resume_checks; }
  else {
    state.checks = state.checks.map((check, index) => {
      if (!check.execution_id || passedCurrent(check)) return check;
      state.check_history ??= []; state.check_history.push(structuredClone(check));
      const saved = record(root, state, `editor-recheck-${generation}-${index}`, 'check', check.title,
        `Level: ${check.level}\n\nCommand argv:\n\n${JSON.stringify(check.command)}\n`, { task_id: state.task_id });
      return { title: check.title, command: check.command, level: check.level, record_id: saved.meta.id, state: 'pending' };
    });
    state.resume_checks = true; delete state.resume_role;
  }
  delete state.interruption;
  state.status = 'working';
  record(root, state, `editor-recovery-${generation}`, 'knowledge', `${state.title}: reconcile stopped editor`,
    `The actual editor-owned native channel or checker ended. Continue ${unfinished ?? 'current independent checks'} with unchanged criteria, retained partial products and unchanged repair allowance.\n`,
    { editor_generation: generation, interruption, effects_hash: checkpoint.effects_hash, repair_attempt: state.repair_attempts ?? 0 });
  save(root, state); return true;
}

function continueNativeRequest(root: string, requestRef: string, automatic: boolean) {
  return locked(root, requestRef, state => {
    if (!automatic && recoverEditorInterruption(root, state, false)) return view(root, state);
    if (automatic && (!state.plan || state.interruption || !['findings', 'uncertain'].includes(state.status))) return view(root, state);
    if (!state.plan || state.interruption || !['findings', 'uncertain'].includes(state.status))
      fail('This continuation requires a retained unfinished native role result.');
    const prior = state.assignments.at(-1);
    if (!prior?.result_hash || prior.state === 'issued') fail('An in-flight or unobserved invocation must be reconciled before continuation.');
    const failedChecks = state.checks.filter(check => check.state === 'failed' && check.result && !check.result.cancelled);
    const professional = prior.state === 'findings' && !!prior.report;
    const incomplete = prior.state === 'uncertain' && prior.invocation?.status === 'returned' && !prior.report;
    const productRepair = failedChecks.length > 0 || professional || incomplete;
    if (automatic && !productRepair) return view(root, state);
    if (productRepair && (state.repair_attempts ?? 0) >= readConfig(root).repair_attempts) {
      if (automatic) return view(root, state);
      throw Object.assign(new Error('The configured implementation repair allowance is spent. Retained products and findings were preserved; no new worker was started.'),
        { code: 'NATIVE_REPAIR_ALLOWANCE_EXHAUSTED' });
    }
    if (state.checks.some(check => check.execution_id && !check.result)) {
      if (automatic) return view(root, state);
      fail('A prior check still has unconfirmed effects; it was not replayed.');
    }
    if (productRepair) state.repair_attempts = (state.repair_attempts ?? 0) + 1;
    delete state.resume_checks;
    state.resume_role = failedChecks.length || professional ? 'WF.FnD' : prior.agentName;
    state.escalate_next = automatic || professional || failedChecks.length > 0;
    state.repair_context = { reports: state.assignments.filter(job => job.report?.verdict === 'findings').slice(-3)
      .map(job => ({ role: job.agentName, report: job.report })),
      checks: state.checks.filter(check => check.state !== 'pending').map(check => ({ title: check.title, state: check.state,
        ...(check.result ? { exit_code: check.result.exit_code } : {}), ...(check.log_path ? { log_path: check.log_path } : {}) })) };
    if (state.checks.some(check => check.execution_id)) {
      state.check_history ??= [];
      state.check_history.push(...structuredClone(state.checks));
      state.generated_hashes = {};
      const attempt = randomUUID();
      state.checks = state.plan.checks.map((check, index) => {
        const saved = record(root, state, `check-${attempt}-${index}`, 'check', check.title,
          `Level: ${check.level}\n\nCommand argv:\n\n${JSON.stringify(check.command)}\n`, { task_id: state.task_id });
        return { ...check, record_id: saved.meta.id, state: 'pending' };
      });
    }
    state.preservation_baseline ??= preservationBaseline(root, state);
    state.status = 'working';
    record(root, state, `continuation-${randomUUID()}`, 'knowledge', `${state.title}: native continuation`,
      `Continue ${state.resume_role} from retained products, professional findings and actual checker results. Criteria and saved plan are unchanged.\n`,
      { prior_assignment_ref: prior.assignment_ref, automatic, repair_attempt: state.repair_attempts,
        output_hashes: fingerprints(root, state.plan.outputs) });
    save(root, state);
    return view(root, state);
  });
}

/** Host-owned callback. Never bind model-provided role, identity, or lifecycle fields. */
export function recordNativeResult(root: string, input: { request_ref: string; assignment_ref: string; invocation: NativeOwnedInvocation;
  raw_result?: unknown; adapter_error?: { code: string; category: string } }) {
  const invocation = input.invocation;
  if (!invocation || invocation.transport !== 'vscode-native' || invocation.tool !== 'runSubagent' || invocation.invoked !== true || !opaque(invocation.host_call_id) ||
      (invocation.native_context_id != null && !opaque(invocation.native_context_id)) ||
      !['returned', 'rejected', 'cancelled', 'uncertain'].includes(invocation.status)) fail('An actual host-owned native invocation outcome is required.');
  if (input.adapter_error && ![input.adapter_error.code, input.adapter_error.category]
    .every(value => typeof value === 'string' && /^[A-Za-z0-9_-]{1,100}$/.test(value)))
    fail('Adapter errors require bounded code and category labels; raw exception messages are not persisted here.');
  const adapterError = input.adapter_error ? { code: input.adapter_error.code, category: input.adapter_error.category } : undefined;
  return locked(root, input.request_ref, state => {
    const assignment = state.assignments.find(item => item.assignment_ref === input.assignment_ref);
    if (!assignment) fail('The host callback does not belong to this request; no state changed.');
    if (invocation.agentName !== assignment.agentName) fail('The actual native call used a different agent than the issued assignment; no state changed.');
    if (invocation.native_agent_name !== undefined && invocation.native_agent_name !== nativeWorkerProfiles[assignment.agentName])
      fail('The actual native worker profile does not match the issued professional role; no state changed.');
    const { report, text } = parseNativeProfessionalReport(input.raw_result), digest = hash(canonical({ invocation, text, adapter_error: adapterError }));
    if (assignment.result_hash) {
      if (assignment.result_hash === digest) return view(root, state);
      fail('This native invocation already has a different retained outcome; no callback was overwritten.');
    }
    if ((assignment.editor_generation ?? 0) !== (state.editor_generation ?? 0))
      fail('An earlier editor generation cannot update the current assignment, task or acceptance.');
    if (state.assignments.some(item => item !== assignment && item.invocation &&
        (item.invocation.host_call_id === invocation.host_call_id ||
          (invocation.native_context_id != null && item.invocation.native_context_id === invocation.native_context_id))))
      fail('Independent roles require separate actual owned native invocations.');
    assignment.invocation = { ...invocation }; assignment.result_hash = digest; assignment.raw_text = text;
    if (adapterError) assignment.adapter_error = adapterError;
    const stable = !state.interruption && selectedSkillsCurrent(root, state) && (assignment.agentName === 'WF.FnD' ||
      matching(root, state, assignment.baseline) && currentMembership(root, state, assignment.context_membership));
    assignment.report = report;
    assignment.state = invocation.status === 'cancelled' ? 'cancelled'
      : invocation.status !== 'returned' || !report || !stable ? 'uncertain'
      : report.verdict === 'pass' && report.findings.length === 0 ? 'completed' : 'findings';
    if (assignment.agentName === 'WF.Tester' && state.tester_evidence?.reassessment_assignment_ref === assignment.assignment_ref)
      state.tester_evidence.status = assignment.state === 'completed' ? 'completed' : assignment.state === 'findings' ? 'findings' : 'uncertain';
    if (assignment.agentName === 'WF.FnD' && assignment.state === 'completed') {
      assignment.baseline = fingerprints(root, state.plan!.outputs);
      state.context_membership = sourceMembership(root, state);
      const missing = Object.entries(assignment.baseline).filter(([, value]) => value === null).map(([path]) => path);
      if (missing.length) {
        assignment.state = 'findings';
        assignment.report = { ...report!, verdict: 'findings', findings: [...report!.findings, `Planned product files are missing: ${missing.join(', ')}`] };
      }
    }
    const saved = record(root, state, `result-${assignment.assignment_ref}`, assignment.agentName === 'WF.Reviewer' ? 'review' : 'knowledge',
      `${assignment.agentName}: ${state.title}`, text || '(No professional report returned.)',
      { task_id: state.task_id, native_assignment_ref: assignment.assignment_ref, native_invocation: invocation, professional_report: assignment.report ?? null,
        output_hashes: assignment.baseline, result_state: assignment.state, adapter_error: adapterError });
    assignment.report_record_id = saved.meta.id;
    const reportStatus = assignment.state === 'completed' ? 'submitted' : 'draft';
    if (saved.meta.status !== reportStatus) saveStatus(root, saved.meta.id, reportStatus);
    if (!state.interruption)
      state.status = assignment.state === 'cancelled' ? 'cancelled' : assignment.state === 'uncertain' ? 'uncertain' : assignment.state === 'findings' ? 'findings' : 'working';
    save(root, state);
    return view(root, state);
  });
}

/** A rejected preflight is not an invocation and must never acquire invented
 * native provenance. Retain the issued assignment and actual configuration issue. */
export function recordNativeDispatchFailure(root: string, input: {
  request_ref: string; assignment_ref: string; code: string; category: string;
}) {
  if (![input.code, input.category].every(value => typeof value === 'string' && /^[A-Za-z0-9_-]{1,100}$/.test(value)))
    fail('Dispatch failure requires a bounded code and category from the native adapter.');
  return locked(root, input.request_ref, state => {
    const assignment = state.assignments.find(item => item.assignment_ref === input.assignment_ref);
    if (!assignment) fail('Dispatch failure does not belong to this request; no state changed.');
    if (assignment.result_hash) return view(root, state);
    if ((assignment.editor_generation ?? 0) !== (state.editor_generation ?? 0))
      fail('An earlier editor generation cannot update current dispatch state.');
    assignment.result_hash = hash(canonical({ code: input.code, category: input.category }));
    assignment.state = input.category === 'cancellation' || input.code === 'CANCELLED' ? 'cancelled' : 'uncertain';
    const saved = record(root, state, `dispatch-${assignment.assignment_ref}`, 'knowledge',
      `${assignment.agentName}: dispatch not started`, `Code: ${input.code}\nCategory: ${input.category}\n\nNo native invocation was observed. Existing artifacts are retained.\n`,
      { native_assignment_ref: assignment.assignment_ref, dispatch_failure: { code: input.code, category: input.category }, invoked: false });
    assignment.report_record_id = saved.meta.id;
    state.status = assignment.state;
    save(root, state);
    return view(root, state);
  });
}

/** Cancellation/editor shutdown is a host event, including between native
 * calls. It preserves real results while preventing a late callback from closing
 * an interrupted request. The host still drains/cancels its actual processes. */
export function interruptNativeRequest(root: string, requestRef: string, input: { code: string; category: string; editor_generation?: number }) {
  if (![input.code, input.category].every(value => typeof value === 'string' && /^[A-Za-z0-9_-]{1,100}$/.test(value)))
    fail('Request interruption requires a bounded host code and category.');
  return locked(root, requestRef, state => {
    if (input.editor_generation !== undefined && (!Number.isSafeInteger(input.editor_generation) || input.editor_generation < 0 ||
        input.editor_generation !== (state.editor_generation ?? 0)))
      throw Object.assign(new Error('A newer controller owns the retained request.'), { code: 'EDITOR_OWNERSHIP_CHANGED' });
    if (state.status === 'accepted') return view(root, state);
    if (state.interruption) {
      if (input.code === 'EDITOR_CLOSED' && input.category === 'cancellation' && state.interruption.code === 'EDITOR_CLOSED' &&
          state.interruption.category === 'cancellation' && !state.interruption.editor_checkpoint) {
        const effects = editorEffectsHash(root, state);
        if (effects) {
          state.status = 'cancelled';
          state.interruption.editor_checkpoint = { generation: state.editor_generation ?? 0, effects_hash: effects,
            inputs: checkInputs(root, state), membership: sourceMembership(root, state) };
          save(root, state);
          record(root, state, `editor-ended-${state.editor_generation ?? 0}`, 'knowledge', `${state.title}: stopped editor effects reconciled`,
            'The retained editor stop intent now has actual settled native/checker outcomes. Original interruption and earlier evidence remain.\n',
            { interruption: state.interruption });
          save(root, state);
        }
      }
      return view(root, state);
    }
    state.interruption = { code: input.code, category: input.category, at: now() };
    const effects = input.code === 'EDITOR_CLOSED' && input.category === 'cancellation' ? editorEffectsHash(root, state) : undefined;
    if (effects) state.interruption.editor_checkpoint = { generation: state.editor_generation ?? 0, effects_hash: effects,
      inputs: checkInputs(root, state), membership: sourceMembership(root, state) };
    state.status = input.code === 'EDITOR_CLOSED' && !effects ? 'uncertain'
      : input.category === 'cancellation' || input.code === 'CANCELLED' ? 'cancelled' : 'uncertain';
    // Publish the stop intent before slower human-readable record indexing.
    // A guardian receipt, not this intent alone, proves checker termination.
    if (input.code === 'EDITOR_CLOSED') save(root, state);
    record(root, state, `interruption-${state.editor_generation ?? 0}-${input.code}`, 'knowledge', `${state.title}: execution interrupted`,
      `Code: ${input.code}\nCategory: ${input.category}\n\nSaved products and observed outcomes are retained. This interruption is not a missing product input.\n`,
      { interruption: state.interruption });
    save(root, state);
    return view(root, state);
  });
}

function checkBinding(state: State, check: Check): DurableCommandBinding {
  if (!check.execution_id || !Number.isSafeInteger(check.durable_generation) || check.durable_generation! < 0)
    fail('The durable check binding is incomplete; no command was replayed.');
  return { workflow_id: state.request_ref, epoch_id: `${state.plan_hash}:${check.durable_generation}`, attempt_id: check.execution_id,
    operation_id: check.record_id, kind: 'check' };
}
function plainCommandResult(result: CommandResult): CommandResult {
  const { exit_code, signal, stdout, stderr, cancelled, timed_out, output_limited, error, duration_ms } = result;
  return { exit_code, signal, stdout, stderr, cancelled, timed_out, output_limited, error, duration_ms };
}
function finalizeNativeCheck(root: string, requestRef: string, index: number, execution: Check, supplied: CommandResult) {
  const result = plainCommandResult(supplied);
  return locked(root, requestRef, state => {
    const check = state.checks[index]!;
    if (check.execution_id !== execution.execution_id) fail('Check execution identity changed; its late result was not assigned elsewhere.');
    if (check.result) {
      if (same(check.result, result)) return check.state;
      fail('This check already retains a different actual result; no evidence was overwritten.');
    }
    if (execution.durable_generation !== (state.editor_generation ?? 0))
      throw Object.assign(new Error('A newer controller owns the retained request; this earlier outcome cannot mutate it.'), { code: 'EDITOR_OWNERSHIP_CHANGED' });
    let current = inputMapsMatch(root, state, checkInputs(root, state), execution.baseline) && currentMembership(root, state) && matching(root, state, execution.generated_inputs ?? {});
    const ended = result.exit_code !== null || result.signal !== null;
    const folder = requestFolderForWorkflow(root, requestRef)!;
    check.log_path = `.workforce/${folder.directory}/native/checks/${execution.execution_id}.log`;
    const key = `evidence-${execution.execution_id}`;
    const prior = loadRecords(root).find(saved => saved.meta.data.workflow_id === requestRef && saved.meta.data.native_operation === key);
    const body = (observed: Check['state']) => `Check log: ${check.log_path}\n\nExit code: ${result.exit_code}\n\nState: ${observed}\n`;
    const log = (observed: Check['state']) => `Command argv: ${JSON.stringify(check.command)}\nExit: ${result.exit_code}\nState: ${observed}\nGenerated outputs: ${JSON.stringify(check.generated_outputs ?? {})}\n\n${result.stdout}\n${result.stderr}`;
    let observed: Check['state'];
    check.result = result;
    if (prior) {
      // Evidence can commit just before the execution-state write is lost. Its
      // original outcome is immutable, even when the user changed inputs since.
      const data = prior.meta.data;
      const retained = (['passed', 'failed', 'uncertain'] as const).find(value => prior.body.replaceAll('\r\n', '\n').trim() === body(value).trim());
      if (!retained || prior.meta.type !== 'evidence' || data.check_id !== check.record_id || data.execution_id !== execution.execution_id ||
          data.log_path !== check.log_path || data.passed !== (retained === 'passed') || !same(data.result, result) ||
          !same(data.output_hashes, execution.baseline) || !same(data.generated_inputs, execution.generated_inputs))
        fail('The retained command evidence does not match this exact outcome; no log or evidence was overwritten.');
      if (data.generated_outputs !== undefined) {
        if (!data.generated_outputs || typeof data.generated_outputs !== 'object' || Array.isArray(data.generated_outputs) ||
            !same(Object.keys(data.generated_outputs).sort(), compilerOutputsFor(root, check).sort()) ||
            Object.values(data.generated_outputs).some(value => value !== null && (typeof value !== 'string' || !/^[a-f0-9]{64}$/.test(value))))
          fail('The retained generated-artifact receipt is invalid; no evidence was overwritten.');
        check.generated_outputs = structuredClone(data.generated_outputs) as Fingerprints;
      }
      const path = safePath(root, check.log_path), info = lstatSync(path), expected = log(retained);
      if (!info.isFile() || info.isSymbolicLink() || info.nlink !== 1 || info.size > 2 * 1024 * 1024 || readFileSync(path, 'utf8') !== expected)
        fail('The retained command log changed; no historical evidence was overwritten.');
      // record() below also verifies its original content digest, title, body
      // and exact professional data before the state can adopt this receipt.
      observed = retained;
      current &&= matching(root, state, check.generated_outputs ?? {});
      check.state = !current || !ended ? 'uncertain' : retained;
      check.log_sha256 = hash(expected);
    } else {
      check.state = !current || !ended || result.cancelled ? 'uncertain'
        : result.exit_code === 0 && !result.error && !result.timed_out && !result.output_limited ? 'passed' : 'failed';
      if (check.state === 'passed') {
        try {
          check.generated_outputs = fingerprints(root, compilerOutputsFor(root, check));
          if (Object.values(check.generated_outputs).some(value => value === null)) check.state = 'failed';
        } catch { check.state = 'uncertain'; }
      }
      observed = check.state;
      const bytes = log(observed); atomicWrite(safePath(root, check.log_path), bytes); check.log_sha256 = hash(bytes);
    }
    const evidence = record(root, state, `evidence-${execution.execution_id}`, 'evidence', check.title,
      body(observed),
      { check_id: check.record_id, execution_id: execution.execution_id, output_hashes: execution.baseline, generated_inputs: check.generated_inputs,
        generated_outputs: check.generated_outputs, passed: observed === 'passed', log_path: check.log_path, result });
    check.evidence_id = evidence.meta.id;
    const status = observed === 'passed' ? 'verified' : 'draft';
    if (evidence.meta.status !== status) saveStatus(root, evidence.meta.id, status);
    if (check.state === 'passed') state.generated_hashes = { ...(state.generated_hashes ?? {}), ...check.generated_outputs };
    if (check.state !== 'passed' && !state.interruption)
      state.status = !current || !ended || check.state === 'uncertain' && !result.cancelled ? 'uncertain' : result.cancelled ? 'cancelled' : 'findings';
    save(root, state); return check.state;
  });
}

function resolveKnownCheckUncertainty(root: string, requestRef: string): State {
  return locked(root, requestRef, current => {
    if (current.interruption?.code !== 'EDITOR_EFFECTS_UNCONFIRMED' || !editorEffectsHash(root, current)) return current;
    current.interruption_history ??= []; current.interruption_history.push(structuredClone(current.interruption));
    delete current.interruption;
    current.status = current.checks.some(check => check.result?.cancelled) ? 'cancelled'
      : current.checks.some(check => check.state === 'failed') ? 'findings' : 'working';
    record(root, current, `durable-known-effects-${hash(canonical(current.checks.map(check => check.execution_id)))}`, 'knowledge', `${current.title}: check effects authenticated`,
      'The previously unavailable exact guardian outcome is now authenticated. Earlier uncertainty is retained as history; no command or specialist was replayed.\n');
    save(root, current); return current;
  });
}

/** Reattach an authenticated outcome, never relaunch an unknown execution. The
 * guardian owns these bytes after editor death; PID absence is not evidence. */
function reconcileNativeCheckReceipts(root: string, requestRef: string): ReturnType<typeof view> | undefined {
  let state = load(root, requestRef), imported = false, ownerDisconnected = false;
  for (const [index, check] of state.checks.entries()) {
    if (!check.execution_id || check.result) continue;
    if (!check.durable_job) editorRecoveryFailure(root, state, 'EDITOR_EFFECTS_UNCONFIRMED');
    let result: DurableCommandResult | undefined;
    try { result = readDurableCommandResult(root, check.durable_job, checkBinding(state, check)); }
    catch { editorRecoveryFailure(root, state, 'EDITOR_EFFECTS_UNCONFIRMED'); }
    if (!result || result.exit_code === null && result.signal === null)
      editorRecoveryFailure(root, state, 'EDITOR_EFFECTS_UNCONFIRMED');
    finalizeNativeCheck(root, requestRef, index, check, result); imported = true;
    state = load(root, requestRef);
    if (!inspectionsCurrent(root, state) || !checkCurrent(root, state, state.checks[index]!) ||
        state.preservation_baseline && !matching(root, state, state.preservation_baseline))
      editorRecoveryFailure(root, state, 'EDITOR_INPUTS_CHANGED');
    if (state.interruption?.code === 'EDITOR_EFFECTS_UNCONFIRMED') state = resolveKnownCheckUncertainty(root, requestRef);
    if (result.durable_reason === 'cancelled' && state.interruption?.code !== 'EDITOR_CLOSED')
      throw Object.assign(new Error('The retained checker was cancelled by its caller, not observed editor loss.'), { code: 'NATIVE_CHECK_CANCELLED' });
    ownerDisconnected ||= result.durable_reason === 'owner-disconnected';
    if (ownerDisconnected || state.interruption?.code === 'EDITOR_CLOSED') {
      interruptNativeRequest(root, requestRef, { code: 'EDITOR_CLOSED', category: 'cancellation' });
      state = load(root, requestRef);
    }
  }
  if (state.interruption) return;
  if (imported && inspectionsCurrent(root, state) && checksCurrentAndPassed(root, state)) return finishNativeRequest(root, requestRef);
  if (imported && state.checks.some(check => check.result?.cancelled)) return;
  if (imported && inspectionsCurrent(root, state) && state.checks.every(check => !check.execution_id || check.state === 'passed' && checkCurrent(root, state, check))) {
    return locked(root, requestRef, current => {
      current.editor_generation = (current.editor_generation ?? 0) + 1;
      current.durable_reconciliation = { generation: current.editor_generation,
        executions: current.checks.flatMap(check => check.execution_id ? [check.execution_id] : []), inputs: checkInputs(root, current), membership: sourceMembership(root, current) };
      current.resume_checks = true; delete current.resume_role; current.status = 'working';
      record(root, current, `durable-check-reconciliation-${current.editor_generation}`, 'knowledge', `${current.title}: retain authenticated check outcome`,
        'Authenticated completed command outcomes were reattached to the same request. Passed effects are retained; only unstarted checks continue. No specialist or completed command was repeated.\n',
        { executions: current.durable_reconciliation.executions, editor_generation: current.editor_generation });
      save(root, current); return view(root, current);
    });
  }
  if (state.status === 'working' && state.resume_checks && state.durable_reconciliation) {
    if (state.durable_reconciliation.generation !== state.editor_generation || !inspectionsCurrent(root, state) ||
        !inputMapsMatch(root, state, checkInputs(root, state), state.durable_reconciliation.inputs) ||
        !currentMembership(root, state, state.durable_reconciliation.membership)) editorRecoveryFailure(root, state, 'EDITOR_INPUTS_CHANGED');
    return view(root, state);
  }
  return;
}

export async function runNativeChecks(root: string, requestRef: string, options: { signal?: AbortSignal; purpose?: 'tester-diagnostic';
  onCheckComplete?: (check: { index: number; title: string; state: string }) => void } = {}) {
  const prepared = locked(root, requestRef, state => {
    if (state.interruption) return;
    assertNativeSkillsCurrent(root, selectedSkills(state));
    if (!(options.purpose === 'tester-diagnostic' ? diagnosticInspectionCurrent(root, state) : inspectionsCurrent(root, state)))
      failInputRevision('Current independent Reviewer and Tester inspection of source and checker inputs is required before executing acceptance checks.');
    if (state.checks.some(check => check.state === 'running')) return;
    return state.checks.map((check, index) => ({ index, check: structuredClone(check), generation: state.editor_generation ?? 0 }));
  });
  if (!prepared) return getNativeRequest(root, requestRef);
  for (const item of prepared) {
    const execution = locked(root, requestRef, state => {
      if (state.interruption) return false;
      if ((state.editor_generation ?? 0) !== item.generation)
        throw Object.assign(new Error('A newer controller owns the request.'), { code: 'EDITOR_OWNERSHIP_CHANGED' });
      assertNativeSkillsCurrent(root, selectedSkills(state));
      const check = state.checks[item.index]!;
      if (!(options.purpose === 'tester-diagnostic' ? diagnosticInspectionCurrent(root, state) : inspectionsCurrent(root, state)) || !knownGeneratedCurrent(root, state)) {
        check.state = 'uncertain'; state.status = 'uncertain';
        record(root, state, `input-change-${check.record_id}`, 'knowledge', `${check.title}: inputs changed before execution`,
          'The inspected source/checker inputs or a previously generated artifact changed. This command was not spawned. Retained evidence is unchanged.');
        save(root, state); return false;
      }
      if (check.state === 'passed' && checkCurrent(root, state, check)) return;
      if (check.execution_id) fail('A prior check execution is retained; automatic replay requires explicit reconciliation.');
      return { ...structuredClone(check), execution_id: randomUUID(), baseline: checkInputs(root, state),
        generated_inputs: { ...(state.generated_hashes ?? {}) }, durable_generation: item.generation, cwd: root };
    });
    if (execution === false) break;
    if (!execution) continue;
    const boundState = load(root, requestRef);
    const result = await runDurableCommand(root, { command: execution.command, cwd: execution.cwd, signal: options.signal,
      binding: checkBinding(boundState, execution), timeout_ms: 60_000, max_output_bytes: 512 * 1024 }, {
      onPrepared: job => locked(root, requestRef, state => {
        const check = state.checks[item.index]!;
        if (state.interruption || (state.editor_generation ?? 0) !== execution.durable_generation || check.execution_id)
          throw Object.assign(new Error('The prepared command no longer owns admission.'), { code: 'EDITOR_OWNERSHIP_CHANGED' });
        if (!inputMapsMatch(root, state, checkInputs(root, state), execution.baseline) || !currentMembership(root, state))
          failInputRevision('Checker inputs changed before durable command admission.');
        Object.assign(check, { execution_id: execution.execution_id, baseline: execution.baseline,
          generated_inputs: execution.generated_inputs, durable_generation: execution.durable_generation, durable_job: job, state: 'running' });
        if (state.editor_recovery) state.editor_recovery.status = 'started';
        save(root, state);
      }),
    });
    const outcome = finalizeNativeCheck(root, requestRef, item.index, execution, result);
    // Later commands may execute an older binary after a failed build. Retain
    // their pending status until a fresh successful prerequisite run.
    try { options.onCheckComplete?.({ index: item.index, title: execution.title, state: outcome }); } catch { /* Observation cannot change the execution outcome. */ }
    if (outcome !== 'passed' || options.signal?.aborted) break;
  }
  return getNativeRequest(root, requestRef);
}

export function finishNativeRequest(root: string, requestRef: string) {
  const completed = locked(root, requestRef, state => {
    if (state.status === 'accepted') return view(root, state);
    assertNativeSkillsCurrent(root, selectedSkills(state));
    if (state.interruption) fail('Interrupted work retains its outcomes and cannot be accepted by a late callback.');
    if (!state.plan || !state.task_id) fail('A professional plan and implementation task are required.');
    if (state.preservation_baseline && !matching(root, state, state.preservation_baseline))
      failInputRevision('An existing protected file changed during implementation; delivery requires reconciliation.');
    if (!currentMembership(root, state)) failInputRevision('Source directory membership changed after independent inspection; current input needs fresh inspection.');
    const required: Role[] = ['WF.FnD', 'WF.Reviewer', 'WF.Tester'];
    const jobs = required.map(role => state.assignments.findLast(item => item.agentName === role));
    if (jobs.some(job => !job || job.state !== 'completed' || job.invocation?.status !== 'returned' ||
        job.report?.verdict !== 'pass' || job.report.findings.length))
      fail('The current product still needs successful owned implementation, independent review and independent Tester results.');
    if (jobs.some(job => !matching(root, state, job!.baseline) || !currentMembership(root, state, job!.context_membership)))
      failInputRevision('The current source/checker revision needs fresh independent inspection.');
    if (new Set(jobs.map(job => job!.invocation!.host_call_id)).size !== required.length)
      fail('Independent owned native calls are required.');
    if (!state.checks.length || !generatedEvidenceCurrent(root, state) || !inspectionsCurrent(root, state) ||
        state.checks.some(check => check.state !== 'passed' || !check.evidence_id || !checkCurrent(root, state, check)))
      fail('Actual passing checks against the current product are required.');
    const baseline = fingerprints(root, state.plan.outputs);
    if (Object.values(baseline).some(value => value === null)) fail('Planned product files are missing.');
    const delivery = record(root, state, `delivery-${hash(canonical(state.checks.map(check => check.execution_id)))}`, 'knowledge', `${state.title}: verified delivery`,
      `${state.plan.summary}\n\nProducts:\n${state.plan.outputs.map(path => `- ${path}`).join('\n')}\n\nAssurance: ${assurance}. Native calls are host-owned observations, not signed provider identities.\n`,
      { output_hashes: baseline, task_id: state.task_id, evidence_ids: state.checks.map(check => check.evidence_id),
        ...(state.skill_contexts ? { native_capability_plan: { schema_version: 1, role_skills: state.plan.role_skills,
          roles: state.skill_contexts, selection: 'explicit-pinned', loaded: 'not-observed', used: 'not-observed', verified: 'not-observed' } } : {}) });
    state.final_report_id = delivery.meta.id;
    // Accepted is a backend decision only after all current-revision conditions.
    const currentReports = new Set(jobs.map(job => job!.report_record_id));
    const currentChecks = new Set(state.checks.flatMap(check => [check.record_id, check.evidence_id]));
    for (const id of state.record_ids) {
      const item = getRecord(root, id);
      if (typeof item.meta.data.native_operation === 'string' && item.meta.data.native_operation.startsWith('delivery') && id !== delivery.meta.id) continue;
      if (item.meta.data.native_assignment_ref && !currentReports.has(id)) continue;
      if (['check', 'evidence'].includes(item.meta.type) && !currentChecks.has(id)) continue;
      const status = item.meta.type === 'task' || id === delivery.meta.id ? 'accepted'
        : item.meta.type === 'evidence' || item.meta.type === 'check' ? 'verified'
        : ['requirement', 'design', 'review'].includes(item.meta.type) ? 'approved' : 'submitted';
      if (item.meta.status !== status) saveStatus(root, id, status);
    }
    if (getRecord(root, state.request_ref).meta.status !== 'accepted') saveStatus(root, state.request_ref, 'accepted');
    state.accepted_hashes = baseline; state.status = 'accepted';
    if (state.input_reconciliation?.status === 'prepared') {
      state.input_reconciliation.status = 'completed';
      state.input_reconciliation.code = 'INPUT_REVISION_VERIFIED';
      state.input_reconciliation.message = 'Current independent inspection and actual checks completed for the reconciled input revision.';
    }
    save(root, state);
    return view(root, state);
  });
  return learnAcceptedRequest(root, completed);
}

/** Reconcile optional metadata after an upgrade without repeating product/model
 * work. Current acceptance is checked again; historical delivery stays intact. */
export function refreshNativeRequestLearning(root: string, requestRef: string) {
  return learnAcceptedRequest(root, getNativeRequest(root, requestRef));
}
function learnAcceptedRequest(root: string, completed: ReturnType<typeof getNativeRequest>) {
  if (!completed.accepted || !completed.plan || !completed.final_report_id) return completed;
  const requestRef = completed.request_ref;
  // Tooling learning is optional and uses only the actual independently
  // inspected files. It cannot invalidate delivery or invent qualification.
  let learned = completed.learning;
  if (!learned || learned.issues.length) {
    try {
      const reviewer = completed.assignments.findLast(job => job.agentName === 'WF.Reviewer')?.baseline ?? {};
      const tester = completed.assignments.findLast(job => job.agentName === 'WF.Tester')?.baseline ?? {};
      const inspected = Object.fromEntries(Object.entries(reviewer).filter(([path, digest]) => tester[path] === digest));
      learned = captureNativeTools(root, { outputs: completed.plan.outputs, inspected });
      locked(root, requestRef, state => {
        if (canonical(state.learning) === canonical(learned)) return;
        if (state.learning) { state.learning_history ??= []; state.learning_history.push({ at: now(), result: state.learning }); }
        state.learning = learned; save(root, state);
      });
    } catch { learned = { candidates: [], issues: ['Optional tool learning was unavailable; verified delivery is retained.'] }; }
  }
  // Search data is derived after real acceptance. A missing/corrupt optional
  // cache cannot turn a verified product back into a runtime blocker.
  try {
    const delivery = getRecord(root, completed.final_report_id);
    saveAcceptedRequestExperience(root, { workflow_id: completed.request_ref, task_family: completed.plan.task_family ?? 'software-tools',
      summary: [completed.plan.summary, ...completed.plan.requirements].join('\n').slice(0, 4000),
      keywords: completed.plan.outputs.slice(0, 40).map(path => path.slice(0, 200)),
      acceptance: { record_id: delivery.meta.id, revision: delivery.meta.revision },
      artifact_paths: completed.plan.outputs, evidence_record_ids: completed.checks.flatMap(check => check.evidence_id ? [check.evidence_id] : []),
      procedures: [...(completed.reuse_execution?.status === 'succeeded' ? [completed.reuse_execution.procedure] : []), ...learned.candidates],
      ...(completed.reuse_execution?.status === 'succeeded' ? { parameters_sha256: completed.reuse_execution.parameters_sha256 } : {}),
      environment: { platform: process.platform, arch: process.arch, client: 'vscode-native', node: process.versions.node },
      usage: { model_calls: completed.assignments.filter(job => job.invocation?.invoked).length } });
    return { ...completed, learning: learned, experience_index: 'saved' as const };
  } catch { return { ...completed, learning: learned, experience_index: 'unavailable' as const }; }
}
