import { z } from 'zod';
import type { ControlledBinding, ControlledReport } from './controlled-tools.js';

const text = z.string().trim().min(1).max(8000);
const optional = <T extends z.ZodType>(schema: T) => schema.nullish();
const professionalResult = z.strictObject({
  summary: text,
  artifacts: optional(z.array(z.string().min(1).max(1024)).max(128)),
  findings: optional(z.array(text).max(64)),
  limitations: optional(z.array(text).max(32)),
  negative_controls: optional(z.array(text).max(32)),
  verdict: optional(z.enum(['pass', 'fail'])),
  failure_kind: optional(z.enum(['implementation', 'checker', 'protocol', 'environment', 'unknown'])),
  product_findings: z.array(z.strictObject({
    path: z.string().min(1).max(1024).describe('Actual affected output or assigned checker path; never a missing tool or future stage.'),
    issue: text.describe('Concrete unresolved defect in this assigned product that prevents a ready handoff.'),
  })).max(64).nullish().describe('Use [] when your assigned product is ready for the next role. Pending independent checks are not product defects.'),
});
type ProfessionalResult = z.infer<typeof professionalResult>;

/** Model supplies professional content. Stage lifecycle is generated by the
 * backend; internal historical ControlledReport remains unchanged. */
export function workforceStageResultSchema(binding: Pick<ControlledBinding, 'stage' | 'role'>): z.ZodObject<z.ZodRawShape> {
  if (['verification', 'review'].includes(binding.stage)) return professionalResult.extend({ verdict: z.enum(['pass', 'fail']) }).superRefine((input, context) => {
    if (input.verdict === 'pass' && input.product_findings?.length)
      context.addIssue({ code: 'custom', path: ['verdict'], message: 'A passing independent verdict cannot retain unresolved product defects.' });
  });
  if (binding.stage === 'diagnosis') return professionalResult.omit({ verdict: true }).extend({ failure_kind: z.enum(['implementation', 'checker', 'protocol', 'environment', 'unknown']) });
  return professionalResult.omit({ verdict: true, failure_kind: true });
}

export function workforceStageReport(binding: Pick<ControlledBinding, 'stage' | 'role'>, value: unknown,
  validateFinding: (finding: { path: string; issue: string }) => void): ControlledReport {
  const input: ProfessionalResult = professionalResult.parse(value);
  const product_findings = input.product_findings ?? [];
  product_findings.forEach(validateFinding);
  // Persist exactly the object that is hashed. Explicit undefined properties
  // disappear on JSON save and would invalidate a later authentic readback.
  const content = { summary: input.summary,
    ...(input.artifacts != null ? { artifacts: input.artifacts } : {}),
    ...(input.findings != null ? { findings: input.findings } : {}),
    ...(input.limitations != null ? { limitations: input.limitations } : {}),
    ...(input.negative_controls != null ? { negative_controls: input.negative_controls } : {}),
    ...(input.verdict != null ? { verdict: input.verdict } : {}) };
  const defects = product_findings.map(item => `${item.path}: ${item.issue}`);
  const failure = defects.length ? binding.stage === 'implementation' || binding.stage === 'synthesis' ? 'implementation'
    : input.failure_kind ?? 'unknown' : input.failure_kind ?? undefined;
  return { ...content, outcome: defects.length && !['review', 'verification', 'diagnosis'].includes(binding.stage) ? 'failed' : 'completed',
    ...(failure ? { failure_kind: failure } : {}), ...(defects.length ? { findings: [...(input.findings ?? []), ...defects] } : {}) };
}

/** One ownership description generated from the same binding as tool exposure. */
export function workforceStageHandoff(binding: ControlledBinding, available?: readonly string[]): string {
  const checks = JSON.stringify(binding.check_titles ?? []);
  if (binding.stage === 'implementation') {
    const operations = JSON.stringify(binding.execution_steps?.map(step => step.title) ?? []);
    const taskRun = available?.includes('task_run') ?? (binding.execution_steps === undefined || !!binding.execution_steps.length);
    return `Your product handoff goes to WF.Reviewer, then WF.Tester. Frozen independent checks ${checks} belong to WF.Tester, which runs them after review through check_run. ` +
      `Required producer operations for your stage: ${operations}. ` +
      (!taskRun ? 'No producer command is required here; task_run is intentionally absent. ' : 'Use task_run only for declared producer operations, never for the later independent checks. ') +
      'Once your outputs and declared producer operations are ready, submit their professional content with product_findings:[] and finish. ' +
      'Pending npm test/compiler/check evidence is expected at this handoff and cannot block it. Do not seek another execution tool or optional plug-in to run the later Tester checks. ' +
      'If your product itself remains defective, list concrete assigned paths and issues in product_findings. The backend owns stage outcome; you do not send outcome or claim final acceptance.';
  }
  if (binding.stage === 'review') return `Review the product before WF.Tester executes ${checks}. Pending future test execution is expected. Supply your independent verdict; backend owns lifecycle and final acceptance.`;
  if (binding.stage === 'verification') return `You own the frozen independent checks ${checks}. Execute them through check_run and give your actual independent verdict; backend owns lifecycle and final acceptance.`;
  if (binding.stage === 'diagnosis') return `Stage ownership is fixed: WF.FnD hands product outputs to WF.Reviewer, then WF.Tester executes frozen checks ${checks} through check_run. ` +
    'This diagnosis is read-only; absence of task_run/check_run in this session is expected. Unexecuted future Tester checks do not establish an environment failure or missing authorization. ' +
    'Classify an environment failure from an actual failed operation or observed missing prerequisite. A prior producer blocking its handoff solely on scheduled independent execution is a stage-contract protocol mismatch. ' +
    'For that mismatch, report failure_kind:protocol and a fresh bounded handoff of the retained product by the original role; backend authenticates its source and effects before rebinding. ' +
    'Supply findings and the professional cause; backend owns the stage outcome and final acceptance.';
  return 'Supply your assigned professional content; backend owns the stage outcome. Do not send outcome or treat later implementation/review/test obligations as missing tools for this stage.';
}
