// Regenerate src/storage/project-guide-skill.ts from .claude/skills/neomind-flow-authoring/SKILL.md. NeoMind installs
// that skill into the projects it configures, so the text ships inside the compiled code (dist/ and the Nimbalyst
// backend bundle) rather than as a file next to it. test/project-guide.test.ts fails while the two differ.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = readFileSync(path.join(root, '.claude/skills/neomind-flow-authoring/SKILL.md'), 'utf8').replace(/\r\n/g, '\n');
const literal = source.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
writeFileSync(path.join(root, 'src/storage/project-guide-skill.ts'), [
  '// Generated by scripts/sync-project-guide.mjs from .claude/skills/neomind-flow-authoring/SKILL.md; edit that file and run',
  '// `node scripts/sync-project-guide.mjs` instead of editing this one.',
  `export const FLOW_AUTHORING_SKILL = \`${literal}\`;`,
  '',
].join('\n'));
